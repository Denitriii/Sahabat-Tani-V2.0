    // mengambil data produk yang terlaku dari database
    private void getDataOpname(DefaultTableModel tabel) {
        
        tabel.setRowCount(0);
        int bulan = cbBulan.getMonth()+1;
        int tahun = cbTahun.getYear();
        String sql = "SELECT * FROM view_laporan_absensi_harian \n" +  
             "WHERE MONTH(tanggal) = ? AND YEAR(tanggal) = ?\n" +
             "ORDER BY tanggal DESC";

        try (PreparedStatement ps = conn.prepareCall(sql)){
            ps.setInt(1, bulan);
            ps.setInt(2, tahun);
            
            
            try(ResultSet rs = ps.executeQuery()) {
                while(rs.next()){
                
                Timestamp tanggal = rs.getTimestamp("tanggal");
                String nama = rs.getString("nama_pegawai");
                Time masuk = rs.getTime("jam_masuk");
                Time pulang = rs.getTime("jam_pulang");
                String status = rs.getString("status");
                
                Object[] row ={nama,tanggal,masuk,pulang,status};
                tabel.addRow(row);
                }
            } 
        } catch (Exception e) {
             e.printStackTrace();
        }
    }
    
