    // mengambil data produk yang terlaku dari database
    private void getDataOpname(DefaultTableModel tabel) {
        
        tabel.setRowCount(0);
        int bulan = cbBulan.getMonth()+1;
        int tahun = cbTahun.getYear();
        String sql = "SELECT * FROM view_opname_owner \n" +  
             "WHERE MONTH(tanggal_opname) = ? AND YEAR(tanggal_opname) = ?\n" +
             "ORDER BY tanggal_opname DESC";

        try (PreparedStatement ps = conn.prepareCall(sql)){
            ps.setInt(1, bulan);
            ps.setInt(2, tahun);
            
            
            try(ResultSet rs = ps.executeQuery()) {
                while(rs.next()){
                String id_opname = rs.getString("id_opname");
                Timestamp tanggal = rs.getTimestamp("tanggal_opname");
                String namaProduk = rs.getString("nama_pupuk");
                int stokSistem = rs.getInt("stokSistem");
                int stokFisik = rs.getInt("stokFisik");
                int selisih = rs.getInt("selisih");
                String keterangan = rs.getString("keterangan");
                
                Object[] row ={id_opname,tanggal,namaProduk,stokSistem,stokFisik,selisih,keterangan};
                tabel.addRow(row);
                }
            } 
        } catch (Exception e) {
             e.printStackTrace();
        }
    }
    
