    public String[] getStatusAbsensiHariIni(String idUser) {
        String[] hasil = new String[2]; // hasil[0] = jam masuk, hasil[1] = status telat/tepat waktu
        LocalDate today = LocalDate.now();

        try {
            String sql = "SELECT waktu_absen, status FROM absensi WHERE id_user = ? AND tanggal = ? AND status = 'masuk'";

            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, idUser);
            ps.setDate(2, Date.valueOf(today));
            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                Time jamMasuk = rs.getTime("waktu_absen");
                String statusDB = rs.getString("status");

                LocalTime waktuMasuk = jamMasuk.toLocalTime();
                hasil[0] = waktuMasuk.format(DateTimeFormatter.ofPattern("HH:mm"));

                LocalTime jamTepat = LocalTime.of(8, 0);
                if (waktuMasuk.isAfter(jamTepat)) {
                   long totalMenitTelat = Duration.between(jamTepat, waktuMasuk).toMinutes();
                    long jam = totalMenitTelat / 60;
                    long menit = totalMenitTelat % 60;

                    if (jam > 0) {
                        hasil[1] = "Terlambat " + jam + " jam " + menit + " menit";
                    } else {
                        hasil[1] = "Terlambat " + menit + " menit";
                    }
                } else {
                    hasil[1] = "Tepat Waktu";
                }
            } else {
                hasil[0] = "-";
                hasil[1] = "Belum Absen Masuk";
            }

        } catch (SQLException e) {
            e.printStackTrace();
        }

        return hasil;
        
    }
    public void cekJamPulangDanDisable() {
        // Tentukan jam pulang
        LocalTime jamPulang = LocalTime.of(16, 0); // 17:00

        // Ambil waktu sekarang
        LocalTime sekarang = LocalTime.now();

        // Cek apakah waktu sekarang sudah lewat jam pulang
        if (sekarang.isBefore(jamPulang)) {
    btnPulang.setEnabled(false); 
    btnPulang.setForeground(Color.gray);
    btnPulang.setText("Belum waktunya");
    } else {
        btnPulang.setEnabled(true);
        btnPulang.setForeground(Color.white);
        btnPulang.setText("Pulang");
    }
    
}
    private boolean sudahAbsenHariIni(String status) {
    String sql = "SELECT COUNT(*) FROM absensi WHERE id_user = ? AND status = ? AND tanggal = ?";
    try (PreparedStatement st = conn.prepareStatement(sql)) {
        st.setString(1, SessionManager.getIdUser());
        st.setString(2, status);
        st.setDate(3, Date.valueOf(LocalDate.now()));

        ResultSet rs = st.executeQuery();
        if (rs.next()) {
            return rs.getInt(1) > 0; // true jika sudah absen
        }
    } catch (SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(null, "Gagal memeriksa presensi!\n" + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    return false; // Jika gagal cek, anggap belum absen
}

