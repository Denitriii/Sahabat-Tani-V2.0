private void loadData() {
        DefaultTableModel model = new DefaultTableModel();
        tblKrg.setModel(model);
        String[] Judul = {
            "Tanggal",
            "Keterangan",
            "jumlah "
                    };
        for (String columnName : Judul) {
            model.addColumn(columnName);
        }
        try {
            
            java.sql.Statement stm = conn.createStatement();
            ResultSet rs = stm.executeQuery("SELECT * FROM pengeluaran");

            while (rs.next()) {
                String tanggal = rs.getString("tanggal");
                String keterangan = rs.getString("keterangan");
                int jumlah  = rs.getInt("jumlah");
                Object[] rowData = {
                   tanggal,
                    keterangan,
                    jumlah
                };
                model.addRow(rowData);
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Database Error: " + ex.getMessage());
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Unexpected Error: " + ex.getMessage());
        }
    }
private void insertData() {
    String keterangan = txtKeterangan.getText();
    String jumlahText = txtJumlah.getText();

    // Validasi untuk memastikan Keterangan dan Jumlah tidak kosong
    if (keterangan.isEmpty() || jumlahText.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Keterangan dan Jumlah wajib diisi!");
        return;
    }

    // Validasi untuk memastikan Keterangan hanya berisi huruf
    if (!keterangan.matches("[a-zA-Z\\s]+")) {
        JOptionPane.showMessageDialog(this, "Keterangan hanya boleh berisi huruf!");
        return;
    }

    try {
        double jumlah = Double.parseDouble(jumlahText);

        // Validasi tambahan: Jumlah tidak boleh kurang dari 500
        if (jumlah < 500) {
            JOptionPane.showMessageDialog(this, "Jumlah minimal harus 500!");
            return;
        }

        
        java.sql.Statement stm = conn.createStatement();
        String sql = "INSERT INTO pengeluaran (keterangan, jumlah, tanggal,id_user) VALUES (?, ?, NOW(),?)";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, keterangan);
        pst.setDouble(2, jumlah);
        pst.setString(3, SessionManager.getIdUser());
        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Data berhasil ditambahkan!");
        txtKeterangan.setText("");
        txtJumlah.setText("");
        loadData();

    } catch (NumberFormatException e) {
        // Tangani jika Jumlah bukan angka
        JOptionPane.showMessageDialog(this, "Jumlah harus angka!");
    } catch (SQLException e) {
        // Tangani kesalahan SQL
        JOptionPane.showMessageDialog(this, "Gagal insert: " + e.getMessage());
    }
}

    

