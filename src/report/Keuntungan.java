private double ambilTotalBiayaKeseluruhan(int bulan,int tahun) {
    double totalHargaBeliRestock = 0.0;
    double totalPengeluaran = 0.0;
    

    try {
        

        // Query restock
        String queryRestock = "SELECT COALESCE(SUM(total_harga), 0) AS total FROM restock WHERE YEAR(tanggal_restock) = ? AND MONTH(tanggal_restock) = ?";
        PreparedStatement pst;
        pst = conn.prepareStatement(queryRestock);
        pst.setInt(1, tahun);
        pst.setInt(2, bulan);
        
        ResultSet rs;
        rs = pst.executeQuery();
        if (rs.next()) totalHargaBeliRestock = rs.getDouble("total");

        rs.close(); pst.close();

        // Query pengeluaran
        String queryPengeluaran = "SELECT COALESCE(SUM(jumlah), 0) AS total FROM pengeluaran WHERE YEAR(tanggal) = ? AND MONTH(tanggal) = ?";
        pst = conn.prepareStatement(queryPengeluaran);
        pst.setInt(1, tahun);
        pst.setInt(2, bulan);
        rs = pst.executeQuery();
        if (rs.next()) totalPengeluaran = rs.getDouble("total");

    } catch (SQLException e) {
        e.printStackTrace();
    } 

    return totalHargaBeliRestock + totalPengeluaran;
}
private void updateGrandTotalHargaTerjualLabel(double total) {
    Locale localeID = new Locale("in", "ID");
    NumberFormat currencyFormat = NumberFormat.getCurrencyInstance(localeID);
    lblTotalHargaTerjual.setText("Total: " + currencyFormat.format(total));
}

private void updateOverallLossLabel(double totalBiaya) {
    Locale localeID = new Locale("in", "ID");
    NumberFormat currencyFormat = NumberFormat.getCurrencyInstance(localeID);
    lblTotalKerugian.setText("Total Biaya (Restock + Pengeluaran): " + currencyFormat.format(totalBiaya));
}
private void calculateAndDisplayNetProfit(double grandTotalHargaTerjual, double totalBiaya) {
    double keuntunganBersih = grandTotalHargaTerjual - totalBiaya;

    Locale localeID = new Locale("in", "ID");
    NumberFormat currencyFormat = NumberFormat.getCurrencyInstance(localeID);

    lblKeuntunganBersih.setText("Keuntungan Bersih: " + currencyFormat.format(keuntunganBersih));

    if (keuntunganBersih < 0) {
        lblKeuntunganBersih.setForeground(new java.awt.Color(204, 0, 0));
    } else {
        lblKeuntunganBersih.setForeground(new java.awt.Color(0, 0, 204));
    }
}


