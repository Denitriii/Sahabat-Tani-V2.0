    private void load_table() {
    DefaultTableModel model = new DefaultTableModel();
    tbl_keun.setModel(model);

    String[] Judul = {
        "Nama Pupuk",
        "Total Terjual",
        "Total Harga Terjual",
        "Harga Jual (Per unit)"
        
    };

    for (String columnName : Judul) {
        model.addColumn(columnName);
    }

    Locale localeID = new Locale("in", "ID");
    NumberFormat numberFormat = NumberFormat.getNumberInstance(localeID);
    DecimalFormat decimalFormat = (DecimalFormat) numberFormat;
    decimalFormat.applyPattern("#,##0.##");

    try {
        String sql = "SELECT * FROM view_laporan_penjualan_pupuk  ";

        java.sql.PreparedStatement pst = conn.prepareStatement(sql);
        
        ResultSet rs = pst.executeQuery();

        while (rs.next()) {
            double totalPenjualan = rs.getDouble("total_penjualan");
            String formattedTotalHarga = decimalFormat.format(totalPenjualan);

            double hargaJual = rs.getDouble("harga_jual");
            String formattedHargaJual = decimalFormat.format(hargaJual);

            double keuntungan = rs.getDouble("keuntungan_bersih");
            String formattedKeuntungan = decimalFormat.format(keuntungan);

            Object[] rowData = {
                rs.getString("nama_pupuk"),
                rs.getInt("total_qty_terjual"),
                formattedTotalHarga,
                formattedHargaJual,
                formattedKeuntungan
            };
            model.addRow(rowData);
        }

    } catch (SQLException ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(null, "Database Error: " + ex.getMessage());
    }
}

