private void filterByMonth() {
    int selectedMonth = moon.getMonth() + 1; // JMonthChooser starts from 0
    int tahun = dcTahun.getYear();
    DefaultTableModel model = new DefaultTableModel();
    tbl_keun.setModel(model);

    double grandTotalHargaTerjual = 0.0;
    double totalBiayaKeseluruhan = 0.0;

    String[] Judul = {
        "Nama Pupuk",
        "Total Terjual",
        "Total Harga Terjual",
        "Harga Jual"
    };
    for (String columnName : Judul) {
        model.addColumn(columnName);
    }

  
    PreparedStatement pst = null;
    ResultSet rs = null;

    try {
        
        String query = "SELECT * FROM view_laporan_penjualan_pupuk WHERE bulan = ? AND tahun = ?";

        pst = conn.prepareStatement(query);
        pst.setInt(1, selectedMonth);
        pst.setInt(2, tahun);
      
        rs = pst.executeQuery();

        Locale localeID = Locale.forLanguageTag("id-ID");
        DecimalFormat decimalFormat = (DecimalFormat) NumberFormat.getNumberInstance(localeID);

        while (rs.next()) {
            double totalHargaTerjual = rs.getDouble("total_penjualan");
            double keuntungan = rs.getDouble("keuntungan_bersih");

            grandTotalHargaTerjual += totalHargaTerjual;

            Object[] rowData = {
                rs.getString("nama_pupuk"),
                rs.getInt("total_qty_terjual"),
                decimalFormat.format(totalHargaTerjual),
                decimalFormat.format(rs.getDouble("harga_jual")),
                decimalFormat.format(keuntungan)
            };
            model.addRow(rowData);
        }

        // Hitung total kerugian (biaya restock + pengeluaran)
        totalBiayaKeseluruhan = ambilTotalBiayaKeseluruhan(selectedMonth,tahun);

        // Update label total penjualan dan kerugian
        updateGrandTotalHargaTerjualLabel(grandTotalHargaTerjual);
        updateOverallLossLabel(totalBiayaKeseluruhan);

        // Hitung dan tampilkan keuntungan bersih
        calculateAndDisplayNetProfit(grandTotalHargaTerjual, totalBiayaKeseluruhan);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Gagal filter data: " + e.getMessage());
        e.printStackTrace();
    } 

    tbl_keun.setModel(model);
}
