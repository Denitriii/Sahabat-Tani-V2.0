    private void btn_printActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_printActionPerformed
       try {
        String jrxmlPath = "src/jasperr/keuntungan5.jrxml";
        String jasperPath = "src/jasperr/keuntungan5.jasper";

        // Compile jrxml ke jasper
        JasperCompileManager.compileReportToFile(jrxmlPath, jasperPath);
        Connection conn = koneksiDB.BukaKoneksi();

        // Ambil nilai tahun dan bulan dari inputan GUI
        int selectedMonth = moon.getMonth() + 1; // moon = JMonthChooser
        int selectedYear = dcTahun.getYear();    // dcTahun = JYearChooser

        // Kirim parameter ke Jasper
        HashMap<String, Object> parameters = new HashMap<>();
        parameters.put("bulan", selectedMonth);
        parameters.put("tahun", selectedYear);

        // Tampilkan laporan
        JasperPrint print = JasperFillManager.fillReport(jasperPath, parameters, conn);
        JasperViewer viewer = new JasperViewer(print, false);
        viewer.setVisible(true);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Error displaying report: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btn_printActionPerformed

