private void loadData() {
    DefaultTableModel model = new DefaultTableModel();
    tbl_rsk.setModel(model);

    String[] Judul = {
        "ID Restock",
        "Tanggal Restock",
        "Jumlah",
        "Harga Beli",
        "Total Harga",
        "Supplier"
    };

    for (String columnName : Judul) {
        model.addColumn(columnName);
    }

    try {
        
        String query = "SELECT * FROM \n" +
                "view_restock_bulanan ";

        ResultSet rs = conn.createStatement().executeQuery(query);

        while (rs.next()) {
            String idRestock = rs.getString("id_restock");
            String tanggalRestock = rs.getString("tanggal_restock");
            int restockQty = rs.getInt("qty");
            int hargaBeli = rs.getInt("harga_beli");
            double totalHarga = rs.getDouble("total_harga");
            String supplier = rs.getString("nama_suplier");

            // Format totalHarga menjadi string dengan format desimal yang sesuai
            String formattedTotalHarga = String.format("%,.2f", totalHarga); // Contoh: 10,000,000.00

            Object[] rowData = {
                idRestock,
                tanggalRestock,
                restockQty,
                hargaBeli,
                formattedTotalHarga, // Gunakan formattedTotalHarga
                supplier,
            };
            model.addRow(rowData);
        }

    } catch (SQLException ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(null, "Database Error: " + ex.getMessage());
    } catch (Exception ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(null, "Unexpected Error: " + ex.getMessage());
    }
}
private void filterByMonth() {
    int selectedMonth = moon.getMonth() + 1; // JMonthChooser starts from 0
    int selectedYear = java.util.Calendar.getInstance().get(java.util.Calendar.YEAR); // Ambil tahun saat ini
    DefaultTableModel model = new DefaultTableModel();

    String[] Judul = {
        "ID Restock",
        "Tanggal Restock",
        "Jumlah",
        "Harga Beli",
        "Total Harga",
        "Supplier"
    };

    for (String columnName : Judul) {
        model.addColumn(columnName);
    }

    try {
        
        String query = "SELECT * FROM\n" +
                "view_restock_bulanan \n" +
                "WHERE MONTH(tanggal_restock) = ? AND YEAR(tanggal_restock) = ?;";

        PreparedStatement pst = conn.prepareStatement(query);
        pst.setInt(1, selectedMonth);
        pst.setInt(2, selectedYear);
        ResultSet rs = pst.executeQuery();

        while (rs.next()) {
            Object[] rowData = {
                rs.getString("id_restock"),
                rs.getString("tanggal_restock"),
                rs.getInt("qty"),
                rs.getInt("harga_beli"),
                String.format("%,.2f", rs.getDouble("total_harga")), // Format total harga menjadi desimal biasa
                rs.getString("nama_suplier")
            };
            model.addRow(rowData);
        }

        tbl_rsk.setModel(model);
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Gagal filter data: " + e.getMessage());
        e.printStackTrace();
    }
}

